import fs from'node:fs';
import assert from'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const teacher=read('teacher.html');
const router=read('teacher-router-v76-2.js');
const version=JSON.parse(read('version.json'));
const scripts=[...teacher.matchAll(/<script[^>]+src="([^"]+)"/g)].map(x=>x[1]);
const styles=[...teacher.matchAll(/<link[^>]+rel="stylesheet"[^>]+href="([^"]+)"/g)].map(x=>x[1]);
assert.equal(version.version,'2026.08.28.76');
assert.equal(version.revision,'76.2-quality-core');
assert.equal(scripts.length,9,'v76.2 adds one persistent router script');
assert.equal(styles.length,12,'v76.2 adds no external stylesheet');
assert.match(teacher,/teacher-router-v76-2\.js\?v=762/);
assert.doesNotMatch(teacher,/tv761NavShield|tv761NavStability/,'v76.1 snapshot shield is retired');
assert.match(router,/stageDashboard/,'dashboard is prepared outside the live shell');
assert.match(router,/replaceChildren\(\.\.\.children\)/,'prepared dashboard replaces main atomically');
assert.match(router,/route===\(core\(\)\?\.state\?\.view\|\|R\.current\)&&ready\(route\)/,'same-route clicks are suppressed');
assert.match(router,/waitUntil/,'route completion is checked frame-by-frame');
assert.match(router,/view==='bank'/);
assert.match(router,/loader\.ensure\('bank'\)/);
assert.doesNotMatch(router,/new MutationObserver|setInterval\(/,'navigation stability adds no observer or polling');
assert.doesNotMatch(router,/location\.(?:reload|replace)/,'navigation never forces a document reload');
assert.doesNotMatch(router,/cloneNode|snapshot\(/,'root cause is fixed instead of visually masked');
